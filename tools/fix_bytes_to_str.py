"""One-off: undo 2to3's fix_types mapping of types.StringType -> bytes.

MGLTools compares against types.StringType for *text*, so the right
Python 3 type is str. The pristine 1.5.6 sources never used the name
``bytes`` in code, so every NAME token ``bytes`` in converted files came
from that fixer. Files written for the port and SWIG output are skipped.
Do not rerun after new code that legitimately uses bytes has been added.
"""
import io
import pathlib
import sys
import tokenize

SRC = pathlib.Path(__file__).resolve().parent.parent / "src"
SKIP_FILES = {"_pyogl.py"}
SKIP_DIRS = {"mglcompat"}


def fix(path):
    text = path.read_text(encoding="utf-8")
    if "generated by SWIG" in text[:300]:
        return 0
    try:
        toks = list(tokenize.generate_tokens(io.StringIO(text).readline))
    except (tokenize.TokenError, SyntaxError):
        return 0
    edits = [(t.start, t.end) for t in toks
             if t.type == tokenize.NAME and t.string == "bytes"]
    if not edits:
        return 0
    lines = text.split("\n")
    for (r, c0), (_, c1) in sorted(edits, key=lambda e: (e[0][0], -e[0][1])):
        lines[r - 1] = lines[r - 1][:c0] + "str" + lines[r - 1][c1:]
    path.write_text("\n".join(lines), encoding="utf-8", newline="")
    return len(edits)


total = 0
for f in SRC.rglob("*.py"):
    if f.name in SKIP_FILES or SKIP_DIRS.intersection(f.parts) or f.parts[-3:-1] == ("opengltk", "OpenGL"):
        continue
    total += fix(f)
print(total, "bytes -> str")
