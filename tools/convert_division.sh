#!/usr/bin/env bash
# Rewrite Python 2 '/' to old_div() (python-future's fix_division_safe), then
# point the import at mglcompat.pydiv (NumPy-aware Python 2 semantics).
# Files written for the port, generated SWIG proxies and mglcompat are skipped.
set -e
cd "$(dirname "$0")/.."
. ~/mglenv/bin/activate
mapfile -t files < <(python - <<'EOF'
import pathlib
skip_dirs = {"mglcompat"}
skip_files = {"src/opengltk/_pyogl.py", "src/opengltk/OpenGL/GL.py",
              "src/opengltk/OpenGL/GLU.py", "src/opengltk/OpenGL/Tk/__init__.py",
              "src/opengltk/extent/_gllib.py", "src/opengltk/extent/_glextlib.py",
              "src/opengltk/extent/_glulib.py"}
for p in sorted(pathlib.Path("src").rglob("*.py")):
    s = str(p).replace("\\", "/")
    if skip_dirs.intersection(p.parts) or s in skip_files:
        continue
    head = p.read_text(encoding="utf-8", errors="replace")[:300]
    if "generated by SWIG" in head:
        continue
    print(s)
EOF
)
echo "${#files[@]} files"
futurize -f libfuturize.fixes.fix_division_safe -w -n --no-diffs "${files[@]}" 2>&1 \
  | grep -E "^RefactoringTool: (Can't|Refactored)" | grep -c Refactored || true
grep -rl "from past.utils import old_div" src | while read -r f; do
  sed -i 's/^\(\s*\)from past\.utils import old_div/\1from mglcompat.pydiv import old_div/' "$f"
done
echo "old_div calls: $(grep -rho 'old_div(' src --include=*.py | wc -l)"
